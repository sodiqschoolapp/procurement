// The outline of the Help page (11-screens-and-ux.md, Help page; build-plan 9.7): its chapters
// and topics in reading order, and for each topic the code items it explains. The words of every
// topic are in src/i18n/help/<language>.json under chapters.<chapter>.topics.<topic>.
//
// `covers` is what the completeness test reads (Help page rule 2: "a test fails when one of these
// has no help entry"): every status, move, permission, Manager right, setting, notification kind,
// warehouse document type and kind of money row of the code, and every page of the app, is named
// by at least one topic. A task that adds one adds it here and writes its words (.claude/rules/ui.md).
//
// Item names: status:, move:<from status>:<action> (a row of ORDER_MOVES), event: (an order's
// History line, ORDER_EVENT_TYPES), permission:, right:, setting:, orderField:, notification:,
// document:, documentStatus:, movement:, moneyRow:, payment:, progress:, writeOff:, entryReason:,
// role:, screen: (the page's folder under src/app), and situation:<edge-cases file>:<row>, a row of
// the situations table of requests-and-approval, purchasing-and-money, warehouse or system
// (plan of 9.7, decided item 12).

